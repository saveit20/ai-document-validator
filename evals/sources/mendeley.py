"""Mendeley 'Samples of electronic invoices' (CC BY 4.0) with katanaml labels (MIT) -> mdl_*.pdf + .expected.json.

Three steps, run in order by default:
  map          invoice number -> PDF name, read from the "Invoice no:" line of each "valid information" PDF
  label        cross-match the katanaml ground truth with the PDFs; a case is dropped, with its reason,
               when the label is empty, the party names disagree with the PDF, or any labelled date, tax
               id or amount is not printed in the PDF (writes labeled.json)
  materialise  write mdl_<invoice_number>.pdf + .expected.json with a per-case rule config and, only
               when --splits-out is given, the dev/test split manifest

  python -m evals.sources.mendeley --raw-dir RAW [--out DIR] [--steps map,label,materialise]
                                   [--splits-out evals/splits.json]

RAW holds mendeley/tnj49gpmtz-2.zip and katanaml/{validation,test}.parquet; the intermediate files
(mendeley/invoice_no_to_pdf.json, mendeley/labeled.json) are written next to them. `label` needs pyarrow.
Configs vary per case so that verdicts are informative: the invoices date from 2011-2021 and are in USD,
so under the brief's config every one would simply FAIL.
"""

import argparse
import datetime as dt
import io
import json
import logging
import random
import re
import shutil
import tempfile
import zipfile
from decimal import Decimal, InvalidOperation
from pathlib import Path

from pypdf import PdfReader

REPO = Path(__file__).resolve().parents[2]
ZIP_NAME = "tnj49gpmtz-2.zip"
VALID_DIR = "Samples of electronic invoices/Dataset with valid information/"
SEED = 20260910
BASE_CONFIG = {
    "document_type": "SUPPLIER_INVOICE",
    "max_age_days": 90,
    "required_fields": ["supplier_name", "invoice_number", "invoice_date", "total_amount"],
}
NUMBER = re.compile(r"\d[\d ]*[.,]\d{2}\b")

LICENSE = """The invoices in this directory are a subset of:

  Kozlowski, Marek; Weichbroth, Pawel (2021), "Samples of electronic invoices",
  Mendeley Data, V2, doi: 10.17632/tnj49gpmtz.2
  https://data.mendeley.com/datasets/tnj49gpmtz/2

licensed under Creative Commons Attribution 4.0 International (CC BY 4.0):
https://creativecommons.org/licenses/by/4.0/

Changes made: a subset of the "valid information" variant was selected and each file was renamed to
mdl_<invoice_number>.pdf. The PDFs themselves are unmodified.

The labels (*.expected.json) are derived from the ground truth published in
katanaml-org/invoices-donut-data-v1 (Hugging Face, MIT licence), cross-checked against the text printed in
each PDF; cases where the label and the PDF disagree were excluded (three that differed only in letter case were
kept, with the printed name). Rule configurations and expected
verdicts were added by this project.

The invoices are synthetic (generated by the dataset authors); they contain no real personal data.
"""


def pdf_text(archive: zipfile.ZipFile, name: str) -> str:
    return "\n".join(
        (p.extract_text() or "") for p in PdfReader(io.BytesIO(archive.read(name))).pages
    )


def build_map(raw_dir: Path) -> None:
    """Write mendeley/invoice_no_to_pdf.json from the printed invoice number of each valid PDF."""
    archive = zipfile.ZipFile(raw_dir / "mendeley" / ZIP_NAME)
    names = sorted(n for n in archive.namelist() if n.startswith(VALID_DIR) and n.endswith(".pdf"))
    mapping = {}
    for name in names:
        page = PdfReader(io.BytesIO(archive.read(name))).pages[0].extract_text() or ""
        match = re.search(r"Invoice no:\s*(\S+)", page)
        assert match, f"{name}: no invoice number printed"
        assert match.group(1) not in mapping, f"{name}: duplicate invoice number {match.group(1)}"
        mapping[match.group(1)] = name
    (raw_dir / "mendeley" / "invoice_no_to_pdf.json").write_text(
        json.dumps(mapping, indent=0), encoding="utf-8"
    )
    print(f"invoice numbers mapped: {len(mapping)}")


def amount(raw: str) -> Decimal:
    digits = raw.replace("$", "").replace("\xa0", "").replace(" ", "").strip()
    if "," in digits and "." in digits:
        digits = digits.replace(".", "")
    return Decimal(digits.replace(",", ".")).quantize(Decimal("0.01"))


def printed_amounts(text: str) -> set[Decimal]:
    found = set()
    for token in NUMBER.findall(text):
        try:
            found.add(amount(token))
        except InvalidOperation:
            continue
    return found


def tax_id(raw: str) -> str:
    return re.sub(r"[\s.\-]", "", raw.upper())


def printed_party(text: str, label: str) -> str | None:
    match = re.search(label + r":\s*\n\s*(.+)", text)
    return match.group(1).strip() if match else None


def header_and_summary(parse: object) -> tuple[dict, dict] | None:
    if not isinstance(parse, dict):
        return None
    if "header" in parse:
        return parse["header"], parse["summary"]
    return parse, parse


def label(raw_dir: Path) -> None:
    """Write mendeley/labeled.json: katanaml labels that are confirmed by the printed PDF."""
    import pyarrow.parquet as pq

    archive = zipfile.ZipFile(raw_dir / "mendeley" / ZIP_NAME)
    pdf_by_number = json.loads(
        (raw_dir / "mendeley" / "invoice_no_to_pdf.json").read_text(encoding="utf-8")
    )
    rows = []
    for split in ("validation", "test"):
        table = pq.read_table(raw_dir / "katanaml" / f"{split}.parquet", columns=["ground_truth"])
        rows += [json.loads(value).get("gt_parse") for value in table.column(0).to_pylist()]

    labeled, dropped = [], []
    for index, parse in enumerate(rows):
        parts = header_and_summary(parse)
        if parts is None:
            dropped.append((f"row {index}", "empty label"))
            continue
        header, summary = parts
        number = header.get("invoice_no")
        pdf_name = pdf_by_number.get(number)
        if pdf_name is None:
            dropped.append((number, "no Mendeley PDF with this invoice number"))
            continue
        text = pdf_text(archive, pdf_name)
        seller, client = printed_party(text, "Seller"), printed_party(text, "Client")
        # Casing differences in the labels are transcription noise; the printed name is the ground truth.
        if (
            not seller
            or not client
            or not header["seller"].casefold().startswith(seller.casefold())
            or not header["client"].casefold().startswith(client.casefold())
        ):
            dropped.append((number, f"party names disagree with the PDF ({seller!r} / {client!r})"))
            continue
        net, vat, gross = (
            amount(summary[key]) for key in ("total_net_worth", "total_vat", "total_gross_worth")
        )
        missing = [
            name
            for name, value in (("net", net), ("vat", vat), ("gross", gross))
            if value not in printed_amounts(text)
        ]
        compact = re.sub(r"[\s.\-]", "", text.upper())
        missing += [
            name
            for name, value in (
                ("seller_tax_id", header["seller_tax_id"]),
                ("client_tax_id", header["client_tax_id"]),
            )
            if tax_id(value) not in compact
        ]
        if header["invoice_date"] not in text:
            missing.append("invoice_date")
        if missing:
            dropped.append(
                (number, f"labelled values not printed in the PDF: {', '.join(missing)}")
            )
            continue
        month, day, year = (int(part) for part in header["invoice_date"].split("/"))
        labeled.append(
            {
                "invoice_number": number,
                "pdf": pdf_name,
                "fields": {
                    "supplier_name": seller,
                    "invoice_number": number,
                    "invoice_date": dt.date(year, month, day).isoformat(),
                    "total_amount": str(gross),
                    "currency": "USD",
                    "tax_id": tax_id(header["seller_tax_id"]),
                    "subtotal_amount": str(net),
                    "tax_amount": str(vat),
                    "customer_name": client,
                    "customer_tax_id": tax_id(header["client_tax_id"]),
                },
                "amounts_add_up": net + vat == gross,
                "day_first_would_misread": day <= 12 and day != month,
            }
        )

    (raw_dir / "mendeley" / "labeled.json").write_text(
        json.dumps(labeled, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    print(
        f"katanaml labels: {len(rows)} | matched and verified against the PDF: {len(labeled)} | dropped: {len(dropped)}"
    )
    for number, reason in dropped:
        print(f"  dropped {number}: {reason}")
    print(f"amounts add up: {sum(c['amounts_add_up'] for c in labeled)}/{len(labeled)}")
    print(
        f"dates a day-first reader would misread: {sum(c['day_first_would_misread'] for c in labeled)}/{len(labeled)}"
    )
    if labeled:
        print("example:", json.dumps(labeled[0]["fields"], ensure_ascii=False))


def config_and_verdict(case_index: int, invoice_date: dt.date) -> tuple[dict, str, str, list[str]]:
    """Cycle through three scenarios so the set contains passes and two kinds of failure."""
    scenario = case_index % 4
    if scenario in (0, 1):
        reference = invoice_date + dt.timedelta(days=30)
        return {**BASE_CONFIG, "allowed_currencies": ["USD"]}, reference.isoformat(), "PASS", []
    if scenario == 2:
        reference = invoice_date + dt.timedelta(days=30)
        return (
            {**BASE_CONFIG, "allowed_currencies": ["EUR", "GBP"]},
            reference.isoformat(),
            "FAIL",
            ["currency_not_allowed"],
        )
    reference = invoice_date + dt.timedelta(days=120)
    return (
        {**BASE_CONFIG, "allowed_currencies": ["USD"]},
        reference.isoformat(),
        "FAIL",
        ["date_out_of_window"],
    )


def materialise(raw_dir: Path, out: Path, holdout: Path, splits_out: Path | None) -> None:
    labeled = json.loads((raw_dir / "mendeley" / "labeled.json").read_text(encoding="utf-8"))
    archive = zipfile.ZipFile(raw_dir / "mendeley" / ZIP_NAME)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / "LICENSE-DATA.txt").write_text(LICENSE, encoding="utf-8")

    order = sorted(labeled, key=lambda case: case["invoice_number"])
    random.Random(SEED).shuffle(order)
    mendeley_ids = []
    for index, case in enumerate(order):
        case_id = f"mdl_{case['invoice_number']}"
        (out / f"{case_id}.pdf").write_bytes(archive.read(case["pdf"]))
        fields = case["fields"]
        config, reference, verdict, extra_tags = config_and_verdict(
            index, dt.date.fromisoformat(fields["invoice_date"])
        )
        tags = ["mendeley_template", *extra_tags]
        if case["day_first_would_misread"]:
            tags.append("us_date")
        spec = {
            "document": f"{case_id}.pdf",
            "source": "mendeley",
            "reference_date": reference,
            "config": config,
            "difficulty": tags,
            "expected": {**fields, "verdict": verdict},
            "notes": "Mendeley 'Samples of electronic invoices' (CC BY 4.0); label from katanaml (MIT), verified against the PDF.",
        }
        (out / f"{case_id}.expected.json").write_text(
            json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        mendeley_ids.append(case_id)
    verdicts = [
        json.loads(p.read_text(encoding="utf-8"))["expected"]["verdict"]
        for p in out.glob("*.expected.json")
    ]
    print(
        f"mendeley cases: {len(mendeley_ids)} | verdicts: "
        + ", ".join(f"{v}={verdicts.count(v)}" for v in ("PASS", "FAIL", "REVIEW"))
    )
    if splits_out is None:
        return

    holdout_ids = sorted(
        path.name.removesuffix(".expected.json") for path in holdout.glob("*.expected.json")
    )
    rng = random.Random(SEED)
    split = {"dev": [], "test": []}
    for group in (
        mendeley_ids,
        [i for i in holdout_ids if i.startswith("hA_")],
        [i for i in holdout_ids if i.startswith("hB_")],
    ):
        shuffled = sorted(group)
        rng.shuffle(shuffled)
        half = len(shuffled) // 2
        split["dev"] += shuffled[:half]
        split["test"] += shuffled[half:]
    manifest = {
        "seed": SEED,
        "method": "each source (Mendeley, holdout batch A, holdout batch B) shuffled with the seed and split in half",
        "sources": {"mendeley": "evals/external/mendeley", "holdout": "evals/holdout"},
        "dev": sorted(split["dev"]),
        "test": sorted(split["test"]),
    }
    splits_out.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"split: dev={len(manifest['dev'])} test={len(manifest['test'])}")
    for name in ("dev", "test"):
        ids = manifest[name]
        print(
            f"  {name}: mendeley={sum(i.startswith('mdl_') for i in ids)} holdout_A={sum(i.startswith('hA_') for i in ids)} holdout_B={sum(i.startswith('hB_') for i in ids)}"
        )


if __name__ == "__main__":
    logging.disable(logging.CRITICAL)
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--raw-dir", type=Path, required=True, help="directory holding mendeley/ and katanaml/"
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(tempfile.gettempdir()) / "evals-sources" / "mendeley",
        help="output directory (deleted and recreated)",
    )
    parser.add_argument(
        "--steps",
        default="map,label,materialise",
        help="comma-separated subset of map,label,materialise",
    )
    parser.add_argument(
        "--holdout-dir",
        type=Path,
        default=REPO / "evals" / "holdout",
        help="held-out cases included in the split manifest",
    )
    parser.add_argument(
        "--splits-out",
        type=Path,
        help="write the dev/test split manifest here (default: not written)",
    )
    args = parser.parse_args()
    steps = set(args.steps.split(","))
    if "map" in steps:
        build_map(args.raw_dir)
    if "label" in steps:
        label(args.raw_dir)
    if "materialise" in steps:
        materialise(args.raw_dir, args.out, args.holdout_dir, args.splits_out)
